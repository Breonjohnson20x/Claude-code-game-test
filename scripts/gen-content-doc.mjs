#!/usr/bin/env node
// Writes docs/CONTENT.md: the game's content as it exists in code, produced by playing a real
// game through the controller. Run after changing any content: `npm run docs:content`.
// Text varies with state (region state, flags, earlier choices); this catalogue shows one
// canonical path and says where variants live.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { newGame, dispatch, getView, TRIAL_FOES } from '../src/game/actions.js';
import { getBeat, EXPEDITION_KINDS, deploymentOffers } from '../src/game/content/expedition.js';
import { getCampfireScene, campfireCompletionEffects } from '../src/game/content/campfire.js';
import { LEGACIES, MAX_LEGACIES } from '../src/game/content/legacies.js';
import { CATEGORY_NAMES, historyCallbacks } from '../src/game/content/crises.js';
import { ARCHETYPES } from '../src/game/duel/archetypes.js';
import { getDuelResult } from '../src/game/duel/engine.js';
import { simulateDuel, createOracleBot } from '../src/game/duel/bots.js';
import { relationshipLabel, attitudeLabel, tensionLabel } from '../src/game/core/relationships.js';
import { CAMPFIRE_THRESHOLD, CAMPFIRE_COOLDOWN_TURNS } from '../src/game/sim/intensity.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = [];
const w = (s = '') => out.push(s);
const run = (s, a) => {
  const r = dispatch(s, a);
  if (r.error) throw new Error(`${a.type}: ${r.error}`);
  return r.state;
};
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const sign = (n) => (n > 0 ? `+${n}` : `${n}`);

/** One effect in compact words. */
function fx(e) {
  switch (e.type) {
    case 'resource':
      return `${e.key} ${sign(e.delta)}`;
    case 'faction': {
      const parts = [];
      if (e.attitude) parts.push(`attitude ${sign(e.attitude)}`);
      if (e.tension) parts.push(`tension ${sign(e.tension)}`);
      for (const [k, v] of Object.entries(e.memory ?? {})) parts.push(`${k} memory ${sign(v)}`);
      return `${e.faction}: ${parts.join(', ')}`;
    }
    case 'relationship':
      return `${e.character}: ${['trust', 'respect', 'affection', 'resentment', 'fear'].filter((k) => e[k]).map((k) => `${k} ${sign(e[k])}`).join(', ')}`;
    case 'memory':
      return `memory ${e.character} ${e.eventId}${e.sentiment !== undefined ? ` (sentiment ${e.sentiment})` : ''}`;
    case 'flag':
      return `flag ${e.key}=${JSON.stringify(e.value)}`;
    case 'counter':
      return `counter ${e.key} ${sign(e.delta ?? 1)}`;
    case 'thread':
      return `thread ${e.thread}${e.urgency ? ` urgency ${sign(e.urgency)}` : ''}${e.status ? ` status=${e.status}` : ''}${e.visibility ? ` visibility=${e.visibility}` : ''}${e.stage ? ` stage ${sign(e.stage)}` : ''}`;
    case 'region':
      return `region${e.state ? ` → ${e.state}` : ''}${e.casualties ? ` casualties +${e.casualties}` : ''}${e.damage ? ` damage +${e.damage}` : ''}${e.monument ? ` monument "${e.monument.title}"` : ''}`;
    case 'intensity':
      return `intensity ${sign(e.delta)}`;
    case 'chronicle':
      return `chronicle "${e.title}" (${e.kind ?? 'event'})`;
    case 'character':
      return `character ${e.character}${e.status ? ` status=${e.status}` : ''}${e.name ? ` name="${e.name}"` : ''}${e.role ? ` role="${e.role}"` : ''}`;
    case 'voice':
      return `voice: ${e.speaker}`;
    default:
      return e.type;
  }
}
const fxList = (list) => (list?.length ? list.map(fx).join('; ') : '—');

function details(summary, lines) {
  w(`<details><summary>${summary}</summary>`);
  w();
  for (const l of lines) w(l);
  w();
  w('</details>');
  w();
}

// ─── Header ───────────────────────────────────────────────────────────────────────────

w('# Content catalogue');
w();
w('> Generated by `npm run docs:content` (`scripts/gen-content-doc.mjs`) from the code, by playing a real game');
w('> through the controller. **Do not edit by hand**; change the content in `src/game/content/*` and regenerate.');
w();
w('Everything a writer or designer needs to review or extend OmniStrat\'s story content: the cast, the factions,');
w('the five-turn arc with every order and its effects, the march, campfire scenes, Legacies and the Passing.');
w('Text often varies with state (region state, flags, earlier choices, reign number). This catalogue follows one');
w('canonical path and notes where variants live. For how the systems work see [GAME_GUIDE.md](GAME_GUIDE.md); for');
w('the effect and action formats see [API.md](API.md).');
w();
w('**Contents:** [Cast and factions](#cast-and-factions) · [The five-turn arc](#the-five-turn-arc) ·');
w('[Deployments](#deployments) · [The march](#the-march) · [Duels](#duels) · [Campfire](#campfire) ·');
w('[Legacies](#legacies) · [Reign II callbacks](#reign-ii-callbacks) · [How to add content](#how-to-add-content)');
w();

// ─── Cast ───────────────────────────────────────────────────────────────────────────────

const s0 = newGame({ seed: 20261024, sovereignName: 'Aurelian' });
w('## Cast and factions');
w();
w('Starting values (`createCharacters` / `createFactions` / `createThreads` in `src/game/core/state.js`).');
w('Relationships are five hidden numbers (trust, respect, affection, resentment, fear) shown only as a tier word.');
w();
w('| id | Name | Role | Age | Status | Starting tier |');
w('|---|---|---|---:|---|---|');
for (const c of Object.values(s0.characters)) w(`| \`${c.id}\` | ${c.name} | ${esc(c.role)} | ${c.age} | ${c.status} | ${relationshipLabel(c.rel)} |`);
w();
w('| Faction id | Name | Leader | Attitude | Tension |');
w('|---|---|---|---|---|');
for (const f of Object.values(s0.factions)) w(`| \`${f.id}\` | ${f.name} | ${f.leader} | ${attitudeLabel(f.attitude)} (${f.attitude}) | ${tensionLabel(f.tension)} (${f.tension}) |`);
w();
w('| Thread id | Title | Visibility | Urgency |');
w('|---|---|---|---:|');
for (const t of Object.values(s0.threads)) w(`| \`${t.id}\` | ${esc(t.title)} | ${t.visibility} | ${t.urgency} |`);
w();
w(`Starting resources: ${Object.entries(s0.resources).map(([k, v]) => `${k} ${v}`).join(', ')}. Year ${s0.year} E.R.`);
w();

// ─── Turns ──────────────────────────────────────────────────────────────────────────────

w('## The five-turn arc');
w();
w('Source: `src/game/content/crises.js` (`turn1` … `turn5`, `getCrisis`). Categories: ' + Object.entries(CATEGORY_NAMES).map(([k, v]) => `\`${k}\` = ${v}`).join(', ') + '.');
w('Each order lists its cost, the Council\'s reactions, its text, the outcome lines shown after it resolves, and its');
w('effects. The resolver also applies economy, threads, events and intensity on top (see GAME_GUIDE.md).');
w('Canonical path: order **E** on turn 1, **A** on turns 2–5. Orders shown are those offered on that path; some');
w('labels, warnings and effects change with flags (for example the Accord, an exposed general, a broken oath).');
w();
let s = s0;
const path = { 1: 'E', 2: 'A', 3: 'A', 4: 'A', 5: 'A' };
for (let turn = 1; turn <= 5; turn += 1) {
  const v = getView(s);
  const c = v.crisis;
  w(`### Turn ${turn} · ${c.title}`);
  w();
  w(`*${c.season} · ${c.location}* · crisis id \`${c.id}\``);
  w();
  for (const line of c.briefing) w(`> ${esc(line)}`);
  w('>');
  w(`> **${esc(c.conflict)}**`);
  w();
  w('Advisors:');
  w();
  for (const a of c.advisors) w(`- **${a.id}**: ${esc(a.line)}`);
  w();
  w('| Order | Category | Cost (treasury / manpower) | Reactions | Warning |');
  w('|---|---|---|---|---|');
  for (const o of c.orders) {
    const r = Object.entries(o.reactions ?? {}).map(([k, x]) => `${k} ${x}`).join(', ');
    w(`| **${o.id}** ${esc(o.label)} | ${o.categoryName} | ${o.cost.treasury} / ${o.cost.manpower} | ${r} | ${esc(o.warning ?? '')} |`);
  }
  w();
  for (const o of c.orders) {
    details(`Order ${o.id}: ${esc(o.label)}`, [
      `*${esc(o.text)}*`,
      '',
      ...o.outcome.map((l) => `> ${esc(l)}`),
      '',
      `**Effects:** ${esc(fxList(o.effects))}`,
    ]);
  }
  s = run(s, { type: 'ISSUE_ORDER', orderId: path[turn] });
  if (s.phase === 'campfire') s = run(s, { type: 'CAMPFIRE_COMPLETE', mode: 'skip' });
  if (turn < 5) s = run(s, { type: 'CONTINUE' });
}

// ─── Deployments ────────────────────────────────────────────────────────────────────────

w('## Deployments');
w();
w('Offered on the Resolution screen by `deploymentOffers(state)` in `src/game/content/expedition.js`:');
w();
w('| Kind | Beats | When offered |');
w('|---|---|---|');
w(`| \`march\` | ${EXPEDITION_KINDS.march.join(' → ')} | turns 1–4, until the march of this reign is done |`);
w(`| \`skirmish\` | ${EXPEDITION_KINDS.skirmish.join(' → ')} | turn 4 |`);
w(`| \`last_stand\` | ${EXPEDITION_KINDS.last_stand.join(' → ')} | turn 5, only when the border outcome is a siege (danger: a loss ends the reign as a fall) |`);
w();
{
  const sd = run(newGame({ seed: 7 }), { type: 'ISSUE_ORDER', orderId: 'A' });
  for (const d of deploymentOffers(sd)) w(`- **${d.title}** (${d.kind}, recommended by ${d.recommender}): ${esc(d.text)} — ${esc(d.line)}`);
  w();
}

// ─── The march ──────────────────────────────────────────────────────────────────────────

w('## The march');
w();
w('Source: `src/game/content/expedition.js` (beat builders `beatRoad` … `beatCamp`). Choice kinds: `talk` (stays on');
w('the beat; each talk choice can be taken once), `advance` (moves on), `duel` (starts a duel; the outcome picks');
w('the next state). Text varies with the region state (STABLE / FORTIFIED / AFTERMATH) and earlier flags; this is');
w('the march taken after order E on turn 1 (region STABLE).');
w();
{
  let m = run(newGame({ seed: 20261024 }), { type: 'ISSUE_ORDER', orderId: 'E' });
  m = run(m, { type: 'BEGIN_DEPLOYMENT', kind: 'march' });
  const take = { road: 'ride_on', checkpoint: 'walk_through', wilds: 'face_alpha', ruin: 'study', champion: 'challenge' };
  const seen = new Set();
  for (let guard = 0; guard < 20 && m.phase === 'expedition'; guard += 1) {
    const beat = getBeat(m);
    const key = `${beat.id}:${m.expedition.phase}`;
    if (!seen.has(key)) {
      seen.add(key);
      w(`### ${beat.title} (\`${beat.id}\`${m.expedition.phase !== 'main' ? `, ${m.expedition.phase}` : ''})`);
      w();
      w(`*${esc(beat.subtitle)}* · scene \`${beat.scene?.beat}\` at ${beat.scene?.timeOfDay}${beat.speaker ? ` · speaker **${beat.speaker.id}**` : ''}`);
      w();
      for (const t of beat.text) w(`> ${esc(t)}`);
      w();
      w('| Choice id | Kind | Label | Hint / warning |');
      w('|---|---|---|---|');
      for (const ch of beat.choices) w(`| \`${ch.id}\` | ${ch.kind} | ${esc(ch.label)} | ${esc([ch.hint, ch.warning].filter(Boolean).join(' · '))} |`);
      w();
      for (const ch of beat.choices) {
        details(`${esc(ch.label)}`, [
          ...(ch.result ?? []).map((l) => `> ${esc(l)}`),
          '',
          `**Effects:** ${esc(fxList(ch.effects))}`,
          ch.kind === 'duel' ? `\n**Duel:** ${esc(JSON.stringify((ch.duel ? ch.duel(m, m.expedition) : null)?.archetypeId ?? 'see duelConfig'))}` : '',
        ]);
      }
    }
    if (m.expedition.pendingDuel) {
      const { duel } = simulateDuel(m.expedition.pendingDuel, createOracleBot({ mode: 'parry' }), { maxMs: 240000 });
      m = run(m, { type: 'EXPEDITION_DUEL_COMPLETE', result: getDuelResult(duel) });
      continue;
    }
    const pick = beat.choices.find((c) => c.id === take[beat.id]) ?? beat.choices.find((c) => c.kind === 'advance' && !c.warning) ?? beat.choices.find((c) => c.kind === 'advance');
    m = run(m, { type: 'EXPEDITION_CHOICE', choiceId: pick.id });
  }
}

// ─── Duels ──────────────────────────────────────────────────────────────────────────────

w('## Duels');
w();
w('Archetypes (`src/game/duel/archetypes.js`); full mechanics in [DUEL.md](DUEL.md).');
w();
w('| id | Name | HP | Poise | Lesson |');
w('|---|---|---:|---:|---|');
for (const a of Object.values(ARCHETYPES)) w(`| \`${a.id}\` | ${a.name} | ${a.maxHp} | ${a.maxPoise} | ${esc(a.lesson)} |`);
w();
w('Trial of Blades sparring partners (`TRIAL_FOES` in `src/game/actions.js`):');
w();
for (const [id, f] of Object.entries(TRIAL_FOES)) w(`- \`${id}\`: **${f.name}** — ${f.epithet}`);
w();

// ─── Campfire ───────────────────────────────────────────────────────────────────────────

w('## Campfire');
w();
w(`Source: \`src/game/content/campfire.js\`. A campfire is offered when NarrativeIntensity reaches ${CAMPFIRE_THRESHOLD} at a quiet`);
w(`moment (cooldown ${CAMPFIRE_COOLDOWN_TURNS} turn(s)); the scene is picked from what happened (\`sceneSpeaker\`). Modes: **enter** (full scene,`);
w('choose a response), **short** (a brief moment) and **skip** (settles intensity, costs nothing). Completion settles');
w(`intensity by ${campfireCompletionEffects(s0, 'enter', 'honest')[0].delta} (enter), ${campfireCompletionEffects(s0, 'short')[0].delta} (short) or ${campfireCompletionEffects(s0, 'skip')[0].delta} (skip).`);
w();
for (const sceneId of ['mara_father', 'mara_mika', 'mara_symbol', 'mara_defeat', 'mara_hard']) {
  const st = { ...s0, phase: 'campfire', campfire: { ...s0.campfire, offer: { sceneId } } };
  const scene = getCampfireScene(st, 'enter');
  w(`### \`${sceneId}\` · ${scene.topic}`);
  w();
  for (const l of scene.lines) w(`> ${esc(l)}`);
  w('>');
  w(`> **${esc(scene.question)}**`);
  w();
  w('| Response | Tone | Label | Effects |');
  w('|---|---|---|---|');
  for (const r of scene.responses) w(`| \`${r.id}\` | ${r.tone} | ${esc(r.label)} | ${esc(fxList(r.effects))} |`);
  w();
  details('Replies', scene.responses.map((r) => `- **${r.tone}:** ${esc(r.reply.join(' '))}`));
}
w('Sparky\'s beat (shown after every non-skip campfire) depends on how Sparky feels: curled in your lap (Fond or cared for');
w('twice), wary at the edge of the light (fear), or stealing dried meat (otherwise). A `lattice` response appears');
w('when the Sovereign holds Architect\'s Mark or studied the ruin.');
w();

// ─── Legacies ───────────────────────────────────────────────────────────────────────────

w('## Legacies');
w();
w(`Source: \`src/game/content/legacies.js\`. At most ${MAX_LEGACIES} carry across the Passing. Each must be earned in play first.`);
w();
w('| id | Name | Earn | Effect | Cost |');
w('|---|---|---|---|---|');
for (const l of Object.values(LEGACIES)) w(`| \`${l.id}\` | ${l.name} | ${esc(l.earn)} | ${esc(l.effect)} | ${esc(l.cost)} |`);
w();

// ─── Reign II ───────────────────────────────────────────────────────────────────────────

w('## Reign II callbacks');
w();
w('`historyCallbacks(state)` in `src/game/content/crises.js` writes the first lines of reign II\'s first briefing from the');
w('previous reign\'s history keys (refugee policy, the checkpoint child, Nyra\'s fate, monuments, civilization memory,');
w('the broken circle). Example, after the canonical reign above passes with an era ending:');
w();
{
  let r = s;
  r = run(r, { type: 'CONTINUE' });
  while (r.phase === 'passing' && r.passing.step !== 'legacies') r = run(r, { type: 'PASSING_NEXT' });
  r = run(r, { type: 'PASSING_CHOOSE_LEGACIES', ids: [] });
  r = run(r, { type: 'BEGIN_NEXT_CYCLE' });
  for (const l of historyCallbacks(r)) w(`> ${esc(l)}`);
  w();
  w(`The new sovereign is **${r.cycle.sovereign.name} ${r.cycle.sovereign.ordinal}**, ${r.year - s.year} years later (${r.year} E.R.).`);
  w(`Characters in reign II: ${Object.values(r.characters).map((c) => `${c.name} (${c.status})`).join(', ')}.`);
  w();
}

// ─── How to add ─────────────────────────────────────────────────────────────────────────

w('## How to add content');
w();
w('- **A new order or a changed one:** edit the turn builder in `src/game/content/crises.js`. Orders are data:');
w('  `{ id, category, label, text, cost, reactions, warning?, effects, outcome, voices }`. Effects use the helpers in');
w('  `src/game/content/effectHelpers.js` (`res`, `rel`, `fac`, `flag`, `counter`, `thread`, `region`, `heat`, `chron`, `mem`,');
w('  `voice`, `character`). Keep one order per category per turn (custom decrees blend orders by category).');
w('- **A march beat or choice:** add a builder in `src/game/content/expedition.js`, register it in `BEATS`, and add its id');
w('  to `EXPEDITION_KINDS`. Add a scenario in `src/game/dev/scenarios.js` so the e2e sweep shows it.');
w('- **A campfire scene:** add it to `SCENES` in `src/game/content/campfire.js` and to `sceneSpeaker`\'s selection.');
w('- **A Legacy:** add it to `LEGACIES` with an `earn` text and a `check(state)`, then apply its effect where it matters');
w('  (`cycle/passing.js` `beginNextCycle`, `sim/resolver.js`, the duel engine via `modifiers.legacies`).');
w('- Then: `npm test`, `npm run docs:content`, `npm run e2e`.');
w();

writeFileSync(join(ROOT, 'docs', 'CONTENT.md'), `${out.join('\n')}\n`);
console.log(`Wrote docs/CONTENT.md (${out.length} lines).`);
